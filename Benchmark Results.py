import random
import time

def randomized_quicksort(arr):
    a = arr.copy()
    stack = [(0, len(a) - 1)]

    while stack:
        lo, hi = stack.pop()

        while lo < hi:
            pivot = a[random.randint(lo, hi)]
            lt, i, gt = lo, lo, hi

            while i <= gt:
                if a[i] < pivot:
                    a[lt], a[i] = a[i], a[lt]
                    lt += 1
                    i += 1
                elif a[i] > pivot:
                    a[i], a[gt] = a[gt], a[i]
                    gt -= 1
                else:
                    i += 1

            left = (lo, lt - 1)
            right = (gt + 1, hi)

            if left[1] - left[0] < right[1] - right[0]:
                if right[0] < right[1]:
                    stack.append(right)
                lo, hi = left
            else:
                if left[0] < left[1]:
                    stack.append(left)
                lo, hi = right

    return a


