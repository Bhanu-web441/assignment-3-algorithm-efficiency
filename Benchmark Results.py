import random

class HashTable:
    def __init__(self, capacity=11):
        self.capacity = capacity
        self.size = 0
        self.prime = 2147483647
        self.a = random.randint(1, self.prime - 1)
        self.b = random.randint(0, self.prime - 1)
        self.table = [[] for _ in range(capacity)]

    def _hash(self, key):
        if not isinstance(key, int):
            raise TypeError("This table requires integer keys.")
        return ((self.a * key + self.b) % self.prime) % self.capacity

    def search(self, key):
        index = self._hash(key)
        for k, value in self.table[index]:
            if k == key:
                return value
        return None

    def insert(self, key, value):
        index = self._hash(key)
        for i, (k, _) in enumerate(self.table[index]):
            if k == key:
                self.table[index][i] = (key, value)
                return

        self.table[index].append((key, value))
        self.size += 1

        if self.size / self.capacity > 0.75:
            self._resize()

    def delete(self, key):
        index = self._hash(key)
        for i, (k, _) in enumerate(self.table[index]):
            if k == key:
                del self.table[index][i]
                self.size -= 1
                return True
        return False

    def _resize(self):
        old_items = [
            item for bucket in self.table for item in bucket
        ]
        self.capacity = self.capacity * 2 + 1
        self.table = [[] for _ in range(self.capacity)]
        self.size = 0

        for key, value in old_items:
            self.insert(key, value)

    def load_factor(self):
        return self.size / self.capacity


# Test the hash table
ht = HashTable()

ht.insert(101, "Chair")
ht.insert(202, "Table")
ht.insert(303, "Sofa")

print("Search 202:", ht.search(202))
print("Delete 101:", ht.delete(101))
print("Search deleted key:", ht.search(101))
print("Load factor:", round(ht.load_factor(), 3))

assert ht.search(202) == "Table"
assert ht.search(101) is None
print("All hash table tests passed.")

import random
import time
import csv
import matplotlib.pyplot as plt

sizes = [100, 500, 1000, 2000]
distributions = [
    "Random",
    "Sorted",
    "Reverse sorted",
    "Repeated elements"
]
results = []
random.seed(42)

for n in sizes:
    for distribution in distributions:
        if distribution == "Random":
            arr = [random.randint(0, n * 10) for _ in range(n)]
        elif distribution == "Sorted":
            arr = list(range(n))
        elif distribution == "Reverse sorted":
            arr = list(range(n, 0, -1))
        else:
            arr = [random.randint(0, 9) for _ in range(n)]

        for name, algorithm in [
            ("Randomized", randomized_quicksort),
            ("Deterministic", deterministic_quicksort)
        ]:
            times = []
            for trial in range(5):
                start = time.perf_counter()
                output = algorithm(arr)
                elapsed = time.perf_counter() - start
                assert output == sorted(arr)
                times.append(elapsed)

            average_ms = sum(times) / len(times) * 1000
            results.append([n, distribution, name, average_ms])
            print(n, distribution, name,
                  f"{average_ms:.3f} ms")

with open("benchmark_results.csv", "w", newline="") as f:
    writer = csv.writer(f)
    writer.writerow([
        "Size", "Distribution", "Algorithm", "Average_ms"
    ])
    writer.writerows(results)

for distribution in distributions:
    plt.figure()
    for name in ["Randomized", "Deterministic"]:
        points = [
            row for row in results
            if row[1] == distribution and row[2] == name
        ]
        plt.plot(
            [row[0] for row in points],
            [row[3] for row in points],
            marker="o",
            label=name
        )

    plt.title(distribution)
    plt.xlabel("Array size")
    plt.ylabel("Average execution time (ms)")
    plt.legend()
    plt.grid(True)
    plt.show()

print("Benchmark results saved.")



